// Bundles the mock WhatsApp page script (src/app.js + the real Lexical editor from node_modules)
// into app.bundle.js, which is committed so the end to end test needs no build step.
//
//   node test/e2e/mocks/whatsapp/build.mjs
import { build } from 'esbuild';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

await build({
  entryPoints: [join(here, 'src', 'app.js')],
  outfile: join(here, 'app.bundle.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'chrome120',
  minify: true,
  legalComments: 'eof', // keep Lexical's MIT notice
  define: { 'process.env.NODE_ENV': '"production"' },
  banner: { js: '/* Generated by build.mjs from src/app.js. Do not edit. */' },
  logLevel: 'info',
});
